"""WHAT THIS GUARDS — the CONSUMERS of a null, which is where every regression lands.

THE INDICTMENT THIS SUITE EXISTS TO ANSWER. Three review rounds running, the vehicle
side was made honest and the whole api suite went green — while the code that READS
those fields crashed, coerced, or quietly disagreed with itself. Making a field
Optional is a change to every file that touches it, and the files that touch it are
never the files anyone is editing. So: the vehicle side is checked by
tests/test_liveness.py (hardware readback -> the JSON on the wire); this checks what
happens to the null AFTERWARDS.

WHAT "AFTERWARDS" TURNED OUT TO MEAN, in the round that produced these tests:

  * POST /api/origin did `round(svc.last_sample.heading_deg, 1)` with no guard, so
    capturing a launch point on a hull whose BNO085 had stopped answering raised a
    TypeError inside the handler — a 500 on the one call that has to succeed before a
    dive can be logged at all. And the field it was writing into could not hold the
    answer anyway: heading0 0.0 is DUE NORTH, which is a bearing, not an admission.
  * nav/calibrate.py read the dive log with `s.get("heading_deg", 0.0)`. A default
    only fires on a MISSING key, and divelog.py writes a dead chip as the key PRESENT
    AND NULL — so the default never fired, the None went into _unwrap's subtraction,
    and `nav.cli calibrate` died on every log from a dive where a sensor stopped. That
    present-versus-absent distinction is the single sharpest edge in this file.
  * /ws/nav and /ws/control described the same vehicle differently in the same tick:
    telemetry said gyro_only=null (navigation cannot say) while the nav frame beside
    it said gyro_only=false (navigation looked, and it is fine). One console reads
    both sockets.
  * a completely healthy boot logged "navigation has STOPPED answering for this hull"
    at WARNING, because the control loop's first tick beat nav_svc.start() to it. A
    warning that fires on every healthy start is a warning nobody reads, and the day
    it means something it will look exactly like the day it did not.
  * and the contract itself: a field that is Optional in protocol.py is only Optional
    if a null actually survives model_validate_json in both directions, with the key
    still ON the wire — a consumer that asks `if "depth" in frame` must not be shown a
    dead sensor as a missing field.

WHY THIS BORROWS test_liveness.Chain RATHER THAN BUILDING ITS OWN VEHICLE. The
consumer side has to be tested against THE SAME chain the producer side is certified
on — one MockHardware, one RovState, one NavService, one estimator, the shipped
fill_nav_fields — or the two halves of this effort are describing two different
submarines and the seam between them is exactly where the last three bugs lived.

NO FIXTURE FILES. The dive log with the dead chips is FLOWN here, through the same
DiveLog the vehicle writes with, with MockHardware._kill_sensor stopping the part
mid-dive. A committed fixture is a file somebody regenerates to make a failing test
pass, and regenerating it IS lowering the bar.

stdlib unittest only, matching the rest of api/tests — see run.py for why there is no
framework here.
"""
