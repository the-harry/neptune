ORIGIN = Origin(lat=52.0, lon=-1.0, accuracy=3.0, source="manual")

# How long the flown fixtures run, in SIMULATED seconds. MockHardware's clock is
# simulated, so this costs microseconds and no test ever sleeps on a wall clock. Long
# enough that the depth and the bearing have both moved a long way from where they
# were when the chip died — a frozen reading and an honest one are only
# distinguishable once the world underneath has moved on.
LEG_S = 8.0


