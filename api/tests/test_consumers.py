# A clean boot says nothing alarming
# ---------------------------------------------------------------------------
BOOT_SETTLE_S = 1.0


class _Capture(logging.Handler):
    def __init__(self) -> None:
        super().__init__(level=logging.NOTSET)
        self.records: list[logging.LogRecord] = []

    def emit(self, record: logging.LogRecord) -> None:
        self.records.append(record)


class CleanBootTest(unittest.TestCase):
    """A WARNING that fires on every healthy start is a warning nobody reads.

    main.py's log_nav_change() says so in its own docstring and then did it anyway: the
    control loop is created BEFORE nav_svc.start() in the lifespan, so its first tick
    found loop_state() == "never-started", took that for a subsystem that had stopped,
    and printed "navigation has STOPPED answering for this hull — speed, snag and
    heading-trust go to cannot-tell" at WARNING on a vehicle where navigation was about
    to come up perfectly. The day that line means something it will look exactly like
    every other day.

    THE REAL BOOT, not a stand-in: `async with main.lifespan(main.app)` is precisely
    what uvicorn does, so this brings up the hardware layer, the control loop, the
    watchdog, the blackbox, the camera plane and navigation, in the shipped order.
    Everything it writes goes into the temp tree at the top of this file.

    WHICH WARNINGS ARE ALLOWED IS TAKEN FROM THE BOOT'S OWN ADMISSIONS rather than from
    a list kept here. This bench has no GPIO and no camera on its network, and saying
    so is TRUE — demanding silence about them would be demanding a lie. So the
    allowance is derived: `hw.is_mock` licenses neptune.hw to complain, `camera.kind ==
    "none"` licenses neptune.cam. Navigation is neither absent nor mocked, and has no
    licence at all.
    """

    @classmethod
    def setUpClass(cls):
        root = logging.getLogger()
        cls._saved_handlers, cls._saved_level = root.handlers[:], root.level
        cls._saved_neptune = logging.getLogger("neptune").level
        # Installed BEFORE main is imported, for two reasons: main.py calls
        # logging.basicConfig() at import, which is a no-op once the root logger already
        # has a handler (so the suite does not spray a page of INFO onto the runner's
        # stderr), and the very first records of the boot are the ones under test.
        cls.cap = _Capture()
        root.handlers = [cls.cap]
        root.setLevel(logging.INFO)
        logging.getLogger("neptune").setLevel(logging.NOTSET)

        import main                        # noqa: PLC0415 — deliberately late; see above

        async def _boot():
            async with main.lifespan(main.app):
                await asyncio.sleep(BOOT_SETTLE_S)
                cls.health = main.app.state.nav_svc.health()
                cls.hw_is_mock = bool(main.app.state.hw.is_mock)
                cls.camera_kind = str(main.app.state.camera.kind)

        asyncio.run(_boot())
        cls.records = list(cls.cap.records)

    @classmethod
    def tearDownClass(cls):
        root = logging.getLogger()
        root.handlers, root.level = cls._saved_handlers, cls._saved_level
        logging.getLogger("neptune").setLevel(cls._saved_neptune)

    def _warnings(self) -> list[logging.LogRecord]:
        return [r for r in self.records if r.levelno >= logging.WARNING]

    def _licensed_prefixes(self) -> tuple[str, ...]:
        out = []
        if self.hw_is_mock:
            out.append("neptune.hw")          # no GPIO on a bench: the fallback IS the news
        # "synthetic" belongs here for exactly the reason the other two do: SyntheticCamera
        # is the animated bench pattern, chosen by get_camera() only when there is NO real
        # camera to open. Its two warnings — picamera2 absent, and the WOLFANG CGI not
        # answering — are the console saying WHY you are looking at a test card, which is
        # news worth having once. Leaving it off this list failed every bench boot on the
        # dev machine, where NEPTUNE_CAM=auto plus an installed Pillow lands on synthetic:
        # a permanently red check, which is the same defect this test exists to prevent,
        # one level up. A warning that always fires gets read past; so does a test that
        # always fails.
        if self.camera_kind in ("none", "mock", "synthetic"):
            out.append("neptune.cam")         # no camera on this network, and it said so
        return tuple(out)

    def test_the_boot_actually_came_up(self):
        # Without this, everything below could pass on a boot that never happened.
        self.assertTrue(any(r.getMessage().startswith("NEPTUNE API up") for r in self.records),
                        "the lifespan never reached the line that says the api is up")
        self.assertTrue(any("control loop @" in r.getMessage() for r in self.records))

    def test_navigation_was_healthy_throughout(self):
        # The premise of the next test: if navigation really HAD stopped, warning about
        # it would be correct and demanding silence would be the bug.
        self.assertEqual(self.health["loop"], "running", self.health)
        self.assertEqual(self.health["tick_faults"], 0, self.health)
        self.assertIsNone(self.health["last_fault"], self.health)
        self.assertIsNone(self.health["loop_end_reason"], self.health)
        self.assertTrue(self.health["reads_vehicle"], self.health)

    def test_a_clean_healthy_boot_logs_no_warning(self):
        licensed = self._licensed_prefixes()
        bad = [r for r in self._warnings() if not r.name.startswith(licensed)]
        self.assertEqual(
            [], [f"{r.levelname} {r.name}: {r.getMessage()}" for r in bad],
            "a boot with nothing wrong with it warned anyway. A warning that fires every "
            "time is a warning that gets read past, and the day one of these means "
            "something it will be indistinguishable from today.\n"
            f"(licensed to complain, from the boot's own report: {list(licensed)} — "
            f"hw_is_mock={self.hw_is_mock}, camera={self.camera_kind!r})")

    def test_navigation_is_not_indicted_before_it_has_been_started(self):
        # Named separately from the sweep above because the failure has a specific shape
        # worth recognising on sight: the control loop is created before nav in the
        # lifespan, so nav's own "never-started" reads to it as a subsystem that died.
        said = [r.getMessage() for r in self.records
                if r.levelno >= logging.WARNING and "navigation" in r.getMessage().lower()]
        self.assertEqual(said, [], "navigation was reported as broken during a boot in "
                                   f"which it came up clean ({self.health}). "
                                   "'Not started yet' and 'stopped answering' are opposite "
                                   "facts about a subsystem and must not share a line.")


