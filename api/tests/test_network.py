# THE SLOW-CONSUMER WINDOW, AND WHY IT IS THIS LONG. Backpressure is not instant: before
# a stopped reader can push back on the server, the client's receive buffer, the
# server's send buffer and asyncio's own write buffer all have to fill, and telemetry is
# a small frame at a modest rate. Measured on the handheld (Windows 11, loopback), a
# client that stops reading takes on the order of ten seconds of held telemetry to reach
# the point where the server's next send blocks. The window is sized from that with
# margin. It is an upper bound on how long the CONDITION takes to arise, not on how long
# the property is checked — the property is checked continuously throughout.
#
# It is honest about what it cannot prove: on a machine with much larger socket buffers
# the window may end before the server is ever pushed back on, and then this class has
# observed a healthy loop under a condition it did not manage to create. The bytes the
# slow socket had queued are drained and reported for exactly that reason, so a green
# result can be read for what it is worth rather than taken on trust.
SLOW_HOLD_S = 15.0
SLOW_RCVBUF = 512  # ask the kernel for the smallest window it will give
SLOW_RESUME_S = 5.0  # after the slow reader drains, telemetry must return
# The largest silence a still-connected client may see on a still-running loop. Two
# seconds is ~30 telemetry periods at the shipped rate: far beyond scheduling jitter,
# far short of "the loop has stopped".
