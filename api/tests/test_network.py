"""WHAT THIS GUARDS — THE SOCKET ITSELF, which nothing in api/tests/ had ever touched.

Every other suite here exercises MODULES. test_liveness drives hardware -> rov ->
protocol and reads the JSON that would have gone on the wire; test_consumers boots the
real lifespan and calls route handlers directly. Both stop one layer short of the thing
the operator actually holds: a TCP connection to a uvicorn server, an HTTP upgrade, a
masked frame, a tether that gets yanked. Everything between `Telemetry.model_dump_json()`
and the bytes arriving at the handheld was unproven — including the four pieces of
api/main.py that exist for nothing else:

  * the `except Exception` around the receive loop, whose entire job is to keep one bad
    socket from taking the app down;
  * `parse_inbound()` returning None and the loop CONTINUING, so a frame the vehicle
    cannot understand costs a frame and not a connection;
  * `ws_unrouted`, added because a websocket upgrade to a typo'd path fell through to
    StaticFiles and answered HTTP 500 with an AssertionError in the log — and a 500 is
    what a BROKEN VEHICLE looks like to a client that retries on a schedule;
  * the watchdog in api/rov.py, which is the only thing standing between a tether that
    died at full throttle and a submarine that keeps going.

None of those can be reached by calling a function. They need a real server, a real
port, and a real client that misbehaves.

HOW THE SERVER IS STOOD UP. `uvicorn.Server` in a thread, over a socket this file bound
to PORT ZERO and then read the assigned port back off. Never a fixed port: a suite that
hardcodes 8000 fails on the one bench where the operator left the real server running,
which is the bench where the tests matter most, and two suites that both hardcode it
cannot run side by side at all. The listening socket is created here rather than by
uvicorn precisely so the port is known BEFORE anything starts serving on it.

What it serves is api/main.py, executed as shipped into an app object of this suite's
own — a FIRST boot, which is what `uvicorn main:app` gets in production and is not the
same operation as re-booting the `main.app` another suite has already used and shut
down. `_load_app_under_test` names the two shipped things that do not survive the
repeat, both of which turned out to be real defects and neither of which is a socket.

Shutdown is in `finally`, always, including the way out of a failed assertion. A test
process that leaves a server holding a port and a control loop turning is a test process
that poisons every run after it.

THE VEHICLE IS FORCED TO MockHardware FOR THIS SUITE, and that is a safety rule, not a
convenience. These checks ARM the vehicle and hold the throttle wide open to prove the
failsafe catches it. Run against `RealHardware` on the Pi that would spin both
propellers in a workshop with somebody's hands near them. The suite is about the
sockets; the hull underneath them is deliberately the simulated one, and it is restored
afterwards.

NO NEW DEPENDENCIES, INCLUDING FOR THE CLIENT. The websocket client below is a few
dozen lines of `socket` and `struct` against RFC 6455. That is not stubbornness: this
suite has to send things a library would refuse to send — a binary frame where the
server expects text, bytes that are not UTF-8, bytes that are not a frame at all — and a
well-behaved client library exists precisely to make those unreachable. It also has to
drop a connection the way a tether does, with a reset and no close handshake, and to
STOP READING while staying connected. Raw sockets are the only way to hold the wrong
end of the protocol on purpose.

stdlib unittest only, matching the rest of api/tests — see run.py for why there is no
framework here.
"""

