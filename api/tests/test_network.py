class FailsafeWatchdogTest(SocketCase):
    """A dead socket must stop the propellers, and it must say so honestly.

    The watchdog in api/rov.py is the only thing between a tether that failed at full
    throttle and a submarine that keeps going, and until this file existed it had never
    been tripped by an actual socket dying — only by advancing a clock in a unit test.
    The two are not the same claim: the watchdog runs on the control loop, and the
    control loop is exactly what a dying socket is capable of disturbing.
    """

    def _drive(self, client: Ws) -> dict:
        client.next_of("telemetry")
        client.send_json({"type": "command", "name": "arm", "c_id": "arm-1"})
        ack = client.next_ack("arm-1")
        self.assertTrue(ack["ok"], f"the vehicle refused to arm: {ack}")
        deadline = time.monotonic() + DEFAULT_TIMEOUT_S
        while time.monotonic() < deadline:
            client.send_json({"type": "control", "throttle": 1.0, "steer": 0.0})
            frame = client.next_of("telemetry")
            if frame["left"] > 0.5 and frame["right"] > 0.5:
                return frame
        raise AssertionError("the vehicle never reported the thrusters running")

    def test_a_a_dead_socket_zeroes_the_thrusters(self):
        client = self.ws()
        driving = self._drive(client)
        self.assertTrue(driving["armed"])
        client.drop_abruptly()
        time.sleep(settings.watchdog_timeout_s + WATCHDOG_SETTLE_S)

        rov = neptune.app.state.rov
        self.assertTrue(rov._failsafe, "the control frames stopped and the failsafe never latched")
        # The reading the operator would see, over a NEW real socket — the failsafe is
        # only worth anything if it reaches the wire.
        back = self.ws()
        frame = back.next_of("telemetry")
        self.assertEqual(
            (0.0, 0.0),
            (frame["left"], frame["right"]),
            "the tether died at full throttle and the vehicle is still " f"driving: {frame['left']} / {frame['right']}",
        )
        # ARMED STAYS TRUE ON PURPOSE. The watchdog zeroes the thrusters; it does not
        # quietly disarm, because "the vehicle is armed and the failsafe is holding it"
        # and "the vehicle is disarmed" are different states and the operator who
        # reconnects has to be told which one they have.
        self.assertTrue(
            frame["armed"],
            "the failsafe disarmed the vehicle instead of zeroing it; the "
            "operator who reconnects cannot tell what state they are in",
        )

    def test_b_control_resuming_clears_the_failsafe(self):
        """Recovery is half the contract, and the half that gets skipped.

        A failsafe that latches and never lets go is its own fault: the tether flaps for
        a second, and the sub is dead in the water until somebody restarts the service.
        """
        client = self.ws()
        self._drive(client)
        client.drop_abruptly()
        time.sleep(settings.watchdog_timeout_s + WATCHDOG_SETTLE_S)
        self.assertTrue(neptune.app.state.rov._failsafe)

        back = self.ws()
        back.next_of("telemetry")
        deadline = time.monotonic() + DEFAULT_TIMEOUT_S
        while time.monotonic() < deadline:
            back.send_json({"type": "control", "throttle": 1.0, "steer": 0.0})
            frame = back.next_of("telemetry")
            if frame["left"] > 0.5:
                self.assertFalse(neptune.app.state.rov._failsafe)
                return
        self.fail("the vehicle never came back after the failsafe, on a reconnected " "socket sending control frames")


