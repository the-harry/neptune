# A real NEPTUNE server, on a real port nobody chose
# ---------------------------------------------------------------------------
class Server:
    """uvicorn on its own thread, bound to a port the OS chose.

    PORT ZERO, READ BACK. The listening socket is created and bound HERE, before uvicorn
    exists, which is the only arrangement in which the assigned port is known before
    anything starts serving on it. Nothing in this file may contain a port number: the
    bench that matters most is the one where the operator has left the real server
    running on 8000, and a suite that collides with it reports a broken vehicle.

    THE EVENT LOOP IS PINNED to stdlib asyncio. uvicorn's "auto" loop calls
    `uvloop.install()` where uvloop is present (the Pi), and that sets a PROCESS-WIDE
    event loop policy which every later `asyncio.run` in this test process would inherit
    — a socket suite quietly changing the loop other suites are measured on. The
    property under test is the app's, not the loop's.
    """

    def __init__(self) -> None:
        self.sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        self.sock.bind((BIND_HOST, 0))
        self.port = self.sock.getsockname()[1]
        self._server = uvicorn.Server(
            uvicorn.Config(
                neptune.app,
                # Nothing printed by the server itself: this runner prints the report, and
                # log_config=None so a test does not reconfigure logging for the process.
                log_config=None,
                log_level="critical",
                access_log=False,
                lifespan="on",
                loop="asyncio",
            )
        )
        self._thread: threading.Thread | None = None

    def start(self) -> "Server":
        self._thread = threading.Thread(
            target=self._server.run, kwargs={"sockets": [self.sock]}, name="neptune-test-server", daemon=True
        )
        self._thread.start()
        deadline = time.monotonic() + SERVER_START_TIMEOUT_S
        while not self._server.started:
            if not self._thread.is_alive():
                raise RuntimeError("the server thread ended before the app came up")
            if time.monotonic() > deadline:
                # WHERE IT IS STUCK, NOT MERELY THAT IT IS. A boot that hangs is the one
                # failure in this file with no wire to inspect and no assertion message
                # to read, and "it did not come up" sends the next person to bisect the
                # suite order by hand — which is exactly what it cost the first time.
                # The server's own thread is the only place the answer can be.
                where = self._server_thread_stack()
                self.stop()
                raise RuntimeError(
                    f"the app did not come up within {SERVER_START_TIMEOUT_S:.0f}s; the "
                    f"server thread was here:\n{where}"
                )
            time.sleep(0.02)
        return self

    def _server_thread_stack(self) -> str:
        ident = self._thread.ident if self._thread is not None else None
        frame = sys._current_frames().get(ident) if ident is not None else None
        if frame is None:
            return "  (the server thread has no frame to report)"
        return "".join(traceback.format_stack(frame))

    def stop(self) -> bool:
        """Ask uvicorn to come down and wait for it. True if the thread actually ended."""
        self._server.should_exit = True
        alive = False
        if self._thread is not None:
            self._thread.join(SERVER_STOP_TIMEOUT_S)
            alive = self._thread.is_alive()
        with contextlib.suppress(OSError):
            self.sock.close()
        return not alive

    # ---- the HTTP plane, over the same real port -------------------------
    def http(self, path: str = "/healthz", timeout: float = DEFAULT_TIMEOUT_S) -> tuple[int, bytes]:
        conn = http.client.HTTPConnection(BIND_HOST, self.port, timeout=timeout)
        try:
            conn.request("GET", path)
            res = conn.getresponse()
            return res.status, res.read()
        finally:
            conn.close()

    def clients(self) -> int:
        status, body = self.http("/healthz")
        if status != 200:
            raise AssertionError(f"/healthz answered {status}, not 200")
        return int(json.loads(body)["clients"])

    def wait_for_clients(self, want: int, timeout: float = CLIENT_SETTLE_S) -> int:
        """Poll until the server agrees how many sockets it is holding."""
        deadline = time.monotonic() + timeout
        seen = -1
        while time.monotonic() < deadline:
            seen = self.clients()
            if seen == want:
                return seen
            time.sleep(0.05)
        return seen


# ONE SERVER, ONE BOOT, FOR THE WHOLE SUITE — AND IT HAS TO BE ONE.
#
# Not a style choice. The app under test has exactly one `app.state`, and its lifespan
# REPLACES hw / rov / manager / camera on the way up and CLOSES the blackbox on the way
# down, so a second server over the same app does not isolate anything, it corrupts what
# is already running: measured, on the first run of this file, a second server booted for
# one class swapped the ConnectionManager out from under the first server's control loop
# and then closed the blackbox that loop was still journalling to. And a second boot is
# not merely redundant, it can HANG — see the note in _load_app_under_test about the
# camera CGI client, which cannot be restarted. A suite that reports the vehicle broken
# because of its own fixture is worse than no suite.
#
# The good side of it: the later checks are served by the same process the malformed
# input was fired at, so an app that quietly died on a bad frame takes the rest of the
# suite with it instead of being replaced by a fresh instance that hides the corpse.
SERVER: Server | None = None
_SAVED: dict = {}


def setUpModule() -> None:
    global SERVER
    # The vehicle is forced to the simulation for the whole suite; see the module
    # docstring. Frozen dataclasses are frozen against accident, not against a test that
    # says why — and every one of these is put back in tearDownModule.
    _SAVED["hardware_backend"] = settings.hardware_backend
    object.__setattr__(settings, "hardware_backend", "mock")
    _SAVED["crt_national_auto"] = nav_settings.crt_national_auto
    object.__setattr__(nav_settings, "crt_national_auto", False)
    # Quiet, deliberately, and put back afterwards. Every check below drives the vehicle
    # into a state it is supposed to complain about — a socket dropped mid-throttle, a
    # frame it cannot parse, a re-arm refused over standing water — so without this the
    # suite prints a page of warnings that are the fixtures working correctly. A test
    # module that permanently silences the vehicle's logger would be a worse bug than
    # the noise, so the level is restored.
    _SAVED["log_levels"] = {
        name: logging.getLogger(name).level for name in ("neptune", "uvicorn.error", "uvicorn.access", "uvicorn.asgi")
    }
    for name in _SAVED["log_levels"]:
        logging.getLogger(name).setLevel(logging.CRITICAL)
    try:
        SERVER = Server().start()
    except BaseException:
        # unittest does not call tearDownModule when setUpModule raised, so everything
        # borrowed above is handed back here or it stays borrowed for the whole run —
        # a suite that could not start its own server must not also leave the next
        # suite's vehicle forced to the simulator and its logger switched off.
        _restore_globals()
        raise


def _restore_globals() -> None:
    for name, level in _SAVED.pop("log_levels", {}).items():
        logging.getLogger(name).setLevel(level)
    if "hardware_backend" in _SAVED:
        object.__setattr__(settings, "hardware_backend", _SAVED.pop("hardware_backend"))
    if "crt_national_auto" in _SAVED:
        object.__setattr__(nav_settings, "crt_national_auto", _SAVED.pop("crt_national_auto"))


def tearDownModule() -> None:
    global SERVER
    stopped = True
    try:
        if SERVER is not None:
            stopped = SERVER.stop()
    finally:
        SERVER = None
        _restore_globals()
    # SAID OUT LOUD, not swallowed. A test process that walks away from a thread still
    # serving a port is a test process that poisons whatever runs next, and "the suite
    # finished" is not the same claim as "the server it started is gone".
    if not stopped:
        raise RuntimeError(
            f"the test server was asked to stop and was still running " f"{SERVER_STOP_TIMEOUT_S:.0f}s later"
        )


def quiesce() -> None:
    """Put the vehicle back where every check expects to find it: disarmed and dry.

    These checks share one server and therefore one RovState, so a check that leaves the
    thrusters armed hands the next one a vehicle it did not set up. Done through the
    state object rather than over a socket because this is fixture work, not a
    measurement — the measurements all go over the wire.
    """
    rov = getattr(neptune.app.state, "rov", None)
    if rov is None:
        return
    hw = neptune.app.state.hw
    if hasattr(hw, "_set_leak"):
        hw._set_leak("NORMAL")
    rov._set_armed(False)
    rov._failsafe = False


class SocketCase(unittest.TestCase):
    """Base: every socket a check opens is closed again, pass or fail."""

    @property
    def server(self) -> Server:
        srv = SERVER
        assert srv is not None, "the server fixture never came up"
        return srv

    def setUp(self) -> None:
        self._open: list[Ws] = []
        quiesce()

    def tearDown(self) -> None:
        for ws in self._open:
            with contextlib.suppress(Exception):
                ws.close()
        quiesce()

    def ws(self, path: str = CONTROL_PATH, **kw) -> Ws:
        client = Ws(self.server.port, path, **kw)
        self._open.append(client)
        return client

    def assert_app_is_still_serving(self, why: str) -> None:
        """The whole point of the malformed-input checks: the APP, not the socket.

        Two independent witnesses, because they fail for different reasons: the HTTP
        plane answering proves the process and the event loop are alive, and a NEW
        control socket being served telemetry proves the control loop is still turning
        and still accepting clients. An app can pass the first and fail the second.
        """
        status, _ = self.server.http("/healthz")
        self.assertEqual(200, status, f"/healthz stopped answering after {why}")
        fresh = self.ws()
        frame = fresh.next_of("telemetry")
        self.assertEqual("telemetry", frame["type"])
        fresh.close_clean()


