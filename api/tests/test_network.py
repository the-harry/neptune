class ControlSocketTest(SocketCase):
    """Connect, be served, go away — including going away badly, over and over.

    THE SEQUENCE NUMBER IS THE POINT OF THE RECONNECT CHECKS. `seq` is what the client's
    gap detector counts on (protocol.py: "monotonically increasing frame number") and
    main.py only advances it while somebody is attached, precisely so a tether dropout
    does not open a hole the client would report as packet loss. Both halves of that are
    checked here: it never goes backwards across a reconnect, and it never skips while
    one client is continuously attached.
    """

    def test_a_a_client_that_connects_is_served_telemetry(self):
        client = self.ws()
        first = client.next_of("telemetry")
        self.assertEqual("telemetry", first["type"])
        # The frame is the shipped contract, not a stub: fields the console cannot
        # render without must be present, and `leak_state` must never be missing —
        # a bool-only client reading an absent stage is the failure protocol.py's
        # UNKNOWN stage exists to prevent.
        for field in ("armed", "left", "right", "leak", "leak_state", "mock", "seq"):
            self.assertIn(field, first, f"the wire frame has no {field!r}")
        self.assertTrue(first["mock"], "this suite must never run against a real hull")

    def test_b_sequence_numbers_do_not_skip_for_an_attached_client(self):
        client = self.ws()
        seqs = [client.next_of("telemetry")["seq"] for _ in range(6)]
        self.assertTrue(all(isinstance(s, int) for s in seqs), seqs)
        self.assertEqual(
            [seqs[0] + i for i in range(len(seqs))],
            seqs,
            "a client that never left was given a gap in the sequence, "
            "which its own gap detector will report as lost packets",
        )

    def test_c_a_clean_close_is_answered_and_the_server_lets_go(self):
        client = self.ws()
        client.next_of("telemetry")
        code = client.close_clean(1000)
        self.assertIn(code, (1000, None), f"the server answered a clean close with {code}")
        self.assertEqual(0, self.server.wait_for_clients(0), "the server is still counting a client that said goodbye")

    def test_d_an_abrupt_drop_is_noticed_and_let_go_of(self):
        client = self.ws()
        client.next_of("telemetry")
        self.assertEqual(1, self.server.wait_for_clients(1))
        client.drop_abruptly()
        self.assertEqual(
            0,
            self.server.wait_for_clients(0),
            "a socket that was reset is still being counted and broadcast "
            "to; a client list that only shrinks on a polite goodbye grows "
            "for the whole of a flaky dive",
        )

    def test_e_telemetry_resumes_and_seq_stays_monotonic_across_reconnect_churn(self):
        """Connect, be served, drop — alternating polite and violent — and again.

        The alternation matters: a clean close and a reset arrive at the server as
        different events (WebSocketDisconnect versus a connection destroyed under it),
        and a vehicle that survives one and not the other survives a tidy laboratory
        and not a canal.
        """
        highest = 0
        for cycle in range(RECONNECT_CHURN):
            client = Ws(self.server.port)
            try:
                seen = [client.next_of("telemetry")["seq"] for _ in range(3)]
                self.assertGreater(
                    seen[0],
                    highest,
                    f"cycle {cycle}: telemetry came back numbered {seen[0]}, at or below "
                    f"the {highest} the last connection had already been shown — a "
                    "sequence that repeats is a gap detector that cannot work",
                )
                self.assertEqual([seen[0] + i for i in range(len(seen))], seen, f"cycle {cycle}: {seen}")
                highest = seen[-1]
            finally:
                if cycle % 2:
                    client.drop_abruptly()
                else:
                    client.close_clean()
            self.server.wait_for_clients(0)


