class MalformedInputTest(SocketCase):
    """Nothing a client can send may take the vehicle down.

    api/main.py has explicit handling for every case below — `parse_inbound` returning
    None, the broad `except Exception` around the receive loop, and `ws_unrouted` — and
    none of it had ever been executed by a test. Handling that is never exercised is
    handling that is believed rather than known, and the failure mode is not subtle: a
    console with a stale URL retries on a schedule, so one wrong path spends the whole
    dive filling the Pi's log with fake internal errors and hiding the real ones.

    The distinction each check draws is between the SOCKET and the APP. Some of these
    inputs legitimately cost the offending connection — a frame the websocket layer
    cannot decode ends that conversation, and should. None of them may cost the vehicle.
    """

    def test_a_a_binary_frame_where_text_was_expected_does_not_take_the_app_down(self):
        client = self.ws()
        client.next_of("telemetry")
        client.send_frame(OP_BINARY, GARBAGE_BYTES)
        # The socket may or may not survive this one — the server asks for text and this
        # is not text. What is not negotiable is the app.
        with contextlib.suppress(Exception):
            client.recv_json(1.0)
        self.assert_app_is_still_serving("a binary frame of arbitrary bytes")

    def test_b_bytes_that_are_not_utf8_do_not_take_the_app_down(self):
        client = self.ws()
        client.next_of("telemetry")
        client.send_frame(OP_TEXT, GARBAGE_BYTES)  # a TEXT frame that is not text
        with contextlib.suppress(Exception):
            client.recv_json(1.0)
        self.assert_app_is_still_serving("a text frame carrying invalid UTF-8")

    def test_c_bytes_that_are_not_a_frame_at_all_do_not_take_the_app_down(self):
        client = self.ws()
        client.next_of("telemetry")
        client.send_raw(GARBAGE_BYTES * 4)  # no framing whatsoever
        with contextlib.suppress(Exception):
            client.recv_json(1.0)
        self.assert_app_is_still_serving("raw bytes that are not a websocket frame")

    def test_d_valid_json_that_is_not_a_message_costs_a_frame_not_the_connection(self):
        """This is the one where the SOCKET must survive too.

        `parse_inbound` answers None for anything that does not match the inbound union
        and main.py `continue`s, which is the whole difference between a console that
        drops a frame and a console that has to reconnect. A client sending a shape the
        vehicle has not heard of is a client running older or newer code, and the answer
        to that is to ignore the frame, not to hang up on the operator.
        """
        client = self.ws()
        before = client.next_of("telemetry")["seq"]
        for blob in JSON_THAT_IS_NOT_A_MESSAGE:
            client.send_text(blob)
        after = client.next_of("telemetry")
        self.assertGreater(
            after["seq"], before, "the socket stopped being served after JSON the vehicle " "could not interpret"
        )
        self.assert_app_is_still_serving("valid JSON that is not an inbound message")

    def test_e_an_unknown_message_type_costs_a_frame_not_the_connection(self):
        client = self.ws()
        before = client.next_of("telemetry")["seq"]
        for blob in UNKNOWN_MESSAGE_TYPES:
            client.send_text(blob)
        after = client.next_of("telemetry")
        self.assertGreater(after["seq"], before, "an unknown message type ended the connection")
        self.assert_app_is_still_serving("an unknown message type")

    def test_f_an_unknown_command_name_is_refused_with_a_reason(self):
        """A command the vehicle does not have is ANSWERED, not dropped.

        The §3 lifecycle is recv -> validate -> apply -> ack, and validate failing is
        still an ack: a console that sent a command and heard nothing cannot tell a
        refusal from a dead tether, and the two need opposite responses from an
        operator.
        """
        name = "do_the_impossible"
        self.assertNotIn(name, COMMAND_NAMES, "pick a name the vehicle really lacks")
        client = self.ws()
        client.next_of("telemetry")
        client.send_json({"type": "command", "name": name, "c_id": "unknown-1"})
        ack = client.next_ack("unknown-1")
        self.assertFalse(ack["ok"], ack)
        self.assertTrue(ack.get("reason"), "a refusal with no reason is a button that " "silently does nothing")
        self.assertEqual(name, ack["name"])

    def test_g_a_websocket_upgrade_to_an_unrouted_path_is_refused_not_crashed(self):
        """A 500 is what a BROKEN VEHICLE looks like. A typo is not a broken vehicle.

        Before `ws_unrouted` existed the upgrade fell through to StaticFiles, whose
        first line asserts the scope is http, and the handshake was answered with HTTP
        500 and a traceback. The client retries on a schedule, so that is not one bad
        line in a log — it is the whole dive's worth of them, on top of the real ones.
        """
        for path in UNROUTED_PATHS:
            with self.subTest(path=path):
                client = self.ws(path)
                self.assertNotEqual(
                    101,
                    client.status,
                    f"{path} accepted a websocket upgrade; this vehicle "
                    "serves /ws/control, /ws/nav and /ws/telemetry",
                )
                self.assertLess(
                    client.status,
                    500,
                    f"{path} answered {client.status_line!r} — a 5xx is the "
                    "vehicle reporting itself broken over a client's typo",
                )
                self.assertGreaterEqual(
                    client.status, 400, f"{path} answered {client.status_line!r}, which " "is not a refusal"
                )
        self.assert_app_is_still_serving("websocket upgrades to unrouted paths")


