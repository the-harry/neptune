# ---------------------------------------------------------------------------
# A websocket client made of nothing but a socket
# ---------------------------------------------------------------------------
class WsClosed(Exception):
    """The server ended this socket. `code` is the close code, or None for an EOF."""

    def __init__(self, code: int | None = None, reason: str = "") -> None:
        super().__init__(f"closed (code={code}) {reason}".strip())
        self.code = code
        self.reason = reason


class Ws:
    """One client connection, held at whatever end of the protocol a test needs.

    Deliberately NOT a well-behaved client. It will send a binary frame where the
    server expects text, bytes that are not UTF-8, and bytes that are not a frame; it
    will stop reading while staying connected; and it will drop the connection with a
    reset and no close handshake, which is what a tether coming out of a socket looks
    like on the wire. A library would make every one of those impossible, and every one
    of them is a thing api/main.py claims to survive.
    """

    def __init__(
        self, port: int, path: str = CONTROL_PATH, *, rcvbuf: int | None = None, timeout: float = DEFAULT_TIMEOUT_S
    ) -> None:
        self.port = port
        self.path = path
        self.timeout = timeout
        self._buf = b""
        self.rcvbuf = -1
        self.response = ""
        self.status_line = ""
        self.status = 0
        self.sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        if rcvbuf is not None:
            # Before connect, so the small window is what gets advertised in the SYN.
            # The kernel is free to clamp this upwards and usually does; what it gives
            # back is read and reported rather than assumed.
            with contextlib.suppress(OSError):
                self.sock.setsockopt(socket.SOL_SOCKET, socket.SO_RCVBUF, rcvbuf)
        self.sock.settimeout(timeout)
        try:
            self._handshake(port, path)
        except BaseException:
            # A connection that never came up must not survive as an open descriptor:
            # this suite opens a lot of sockets deliberately badly, and a leaked one
            # keeps the server counting a client that is not there.
            self.close()
            raise

    def _handshake(self, port: int, path: str) -> None:
        self.sock.connect((BIND_HOST, port))
        self.rcvbuf = self.sock.getsockopt(socket.SOL_SOCKET, socket.SO_RCVBUF)
        key = base64.b64encode(os.urandom(16)).decode("ascii")
        self.sock.sendall(
            f"GET {path} HTTP/1.1\r\n"
            f"Host: {BIND_HOST}:{port}\r\n"
            "Upgrade: websocket\r\n"
            "Connection: Upgrade\r\n"
            f"Sec-WebSocket-Key: {key}\r\n"
            "Sec-WebSocket-Version: 13\r\n\r\n".encode("ascii")
        )
        head = b""
        while b"\r\n\r\n" not in head:
            chunk = self.sock.recv(4096)
            if not chunk:
                break
            head += chunk
        head, _, self._buf = head.partition(b"\r\n\r\n")
        self.response = head.decode("latin-1")
        self.status_line = self.response.splitlines()[0] if self.response else ""
        try:
            self.status = int(self.status_line.split(" ")[1])
        except (IndexError, ValueError):
            self.status = 0

    # ---- raw plumbing ----------------------------------------------------
    @staticmethod
    def _frame(opcode: int, payload: bytes) -> bytes:
        """One final, masked client frame. Clients MUST mask (RFC 6455 §5.3)."""
        n = len(payload)
        out = bytes([0x80 | opcode])
        if n < 126:
            out += bytes([0x80 | n])
        elif n <= 0xFFFF:
            out += bytes([0x80 | 126]) + struct.pack("!H", n)
        else:
            out += bytes([0x80 | 127]) + struct.pack("!Q", n)
        mask = os.urandom(4)
        return out + mask + bytes(b ^ mask[i % 4] for i, b in enumerate(payload))

    def send_frame(self, opcode: int, payload: bytes) -> None:
        self.sock.sendall(self._frame(opcode, payload))

    def send_raw(self, blob: bytes) -> None:
        """Bytes straight onto the connection, with no framing at all."""
        self.sock.sendall(blob)

    def send_text(self, text: str) -> None:
        self.send_frame(OP_TEXT, text.encode("utf-8"))

    def send_json(self, obj: dict) -> None:
        self.send_text(json.dumps(obj))

    def _fill(self, deadline: float) -> None:
        left = deadline - time.monotonic()
        if left <= 0:
            raise TimeoutError(f"nothing arrived on {self.path} before the deadline")
        self.sock.settimeout(left)
        chunk = self.sock.recv(65536)
        if not chunk:
            raise WsClosed(None, "the peer closed the stream without a close frame")
        self._buf += chunk

    def _need(self, n: int, deadline: float) -> None:
        while len(self._buf) < n:
            self._fill(deadline)

    def recv_frame(self, deadline: float) -> tuple[int, bytes]:
        self._need(2, deadline)
        opcode = self._buf[0] & 0x0F
        n = self._buf[1] & 0x7F
        off = 2
        if n == 126:
            self._need(4, deadline)
            n = struct.unpack("!H", self._buf[2:4])[0]
            off = 4
        elif n == 127:
            self._need(10, deadline)
            n = struct.unpack("!Q", self._buf[2:10])[0]
            off = 10
        self._need(off + n, deadline)
        payload = self._buf[off : off + n]
        self._buf = self._buf[off + n :]
        return opcode, payload

    def recv_json(self, timeout: float | None = None) -> dict:
        """The next application message, answering pings on the way past."""
        deadline = time.monotonic() + (self.timeout if timeout is None else timeout)
        while True:
            opcode, payload = self.recv_frame(deadline)
            if opcode == OP_PING:
                self.send_frame(OP_PONG, payload)
                continue
            if opcode == OP_PONG:
                continue
            if opcode == OP_CLOSE:
                code = struct.unpack("!H", payload[:2])[0] if len(payload) >= 2 else None
                raise WsClosed(code, payload[2:].decode("utf-8", "replace"))
            return json.loads(payload.decode("utf-8"))

    def next_of(self, kind: str, timeout: float | None = None) -> dict:
        """The next message of one `type`, skipping the rest of the stream."""
        deadline = time.monotonic() + (self.timeout if timeout is None else timeout)
        while True:
            left = deadline - time.monotonic()
            if left <= 0:
                raise TimeoutError(f"no {kind!r} message arrived on {self.path} in time")
            msg = self.recv_json(left)
            if msg.get("type") == kind:
                return msg

    def next_ack(self, c_id: str, timeout: float | None = None) -> dict:
        deadline = time.monotonic() + (self.timeout if timeout is None else timeout)
        while True:
            left = deadline - time.monotonic()
            if left <= 0:
                raise TimeoutError(f"no ack for c_id={c_id!r} arrived in time")
            msg = self.recv_json(left)
            if msg.get("type") == "ack" and msg.get("c_id") == c_id:
                return msg

    # ---- the three ways a client can go away ------------------------------
    def close_clean(self, code: int = 1000, timeout: float = DEFAULT_TIMEOUT_S) -> int | None:
        """The polite goodbye: a close frame, and the server's echo read back."""
        deadline = time.monotonic() + timeout
        echoed: int | None = None
        try:
            self.send_frame(OP_CLOSE, struct.pack("!H", code))
            while True:
                opcode, payload = self.recv_frame(deadline)
                if opcode == OP_CLOSE:
                    if len(payload) >= 2:
                        echoed = struct.unpack("!H", payload[:2])[0]
                    break
        except (OSError, TimeoutError, WsClosed):
            pass
        finally:
            self.close()
        return echoed

    def drop_abruptly(self) -> None:
        """What a tether does: a reset, no close frame, nothing said.

        SO_LINGER with a zero timeout makes close() send RST instead of FIN, so the
        server sees the connection destroyed rather than shut down — the same event a
        yanked Ethernet plug or a dead Pi produces, and a strictly harsher one than the
        FIN a plain close() would send.

        BOTH LAYOUTS OF `struct linger` ARE TRIED, because they genuinely differ: it is
        two ints on POSIX and two u_shorts in Winsock, and the wrong width is rejected
        with the option unset. Silently falling back to a plain close would still end
        the connection, but it would end it politely — this suite would then be checking
        the tidy case twice and the violent one never, on the platform this repo is
        developed on. If neither is accepted the close still happens; what is lost is
        only the harshness, and never the test.
        """
        for layout in ("ii", "hh"):
            try:
                self.sock.setsockopt(socket.SOL_SOCKET, socket.SO_LINGER, struct.pack(layout, 1, 0))
                break
            except OSError:
                continue
        self.close()

    def drain(self, quiet_for: float = 1.0, limit: float = 20.0) -> int:
        """Read everything queued and say how much there was. Ends a slow-reader hold."""
        total = 0
        end = time.monotonic() + limit
        self.sock.settimeout(quiet_for)
        while time.monotonic() < end:
            try:
                chunk = self.sock.recv(1 << 16)
            except (TimeoutError, OSError):
                break
            if not chunk:
                break
            total += len(chunk)
        self.sock.settimeout(self.timeout)
        return total

    def close(self) -> None:
        with contextlib.suppress(OSError):
            self.sock.close()


