def _load_app_under_test():
    """Execute api/main.py into an app object of this suite's own, and return it.

    NOT `import main`, and the difference is the whole reason this function exists.
    `main.app` is a module-level singleton with module-level state hanging off it — one
    BlackBox, one ConnectionManager, one NavService, one camera control plane — and by
    the time this suite runs, another suite in the same process has usually already
    booted that app's lifespan and shut it down again. Booting it a SECOND time is not
    the same operation as booting it once, and two of the things it wakes up do not
    survive the repeat:

      * the lifespan CLOSES `app.state.bb` on the way out, and `ws_control` journals
        every new client before its own try-block — so the first socket this suite
        opened died on `I/O operation on closed file` and took the control loop with it;
      * `api/camera/cgi.py` cannot be restarted at all. `CgiClient.aclose()` cancels the
        queue worker and leaves `self._worker` pointing at the dead task, so the next
        `start()` sees a non-None worker and creates nothing — and `_enqueue` then puts
        a job on a queue nobody is reading and awaits its future with no timeout. The
        camera service's `refresh_menu()` on startup therefore never returns and the
        app never finishes coming up. It is INTERMITTENT, which is worse: `_enqueue`
        short-circuits while the circuit breaker is still open, so a second boot a few
        seconds after the first raises and carries on, and a second boot minutes later
        hangs forever. Measured both ways in one afternoon.

    Neither of those is a socket, and neither is this suite's to fix. api/main.py is
    executed here exactly as shipped — the same file, the same statements, in the same
    order — and what comes out is a first boot of a fresh app, which is precisely what
    `uvicorn main:app` gets in production. Nothing is stubbed and nothing is skipped.
    """
    path = Path(__file__).resolve().parent.parent / "main.py"
    spec = importlib.util.spec_from_file_location("neptune_main_under_test", path)
    if spec is None or spec.loader is None:  # pragma: no cover — main.py is right there
        raise ImportError(f"could not load the app under test from {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


# api/main.py runs `logging.basicConfig()` when it executes, and this module has to
# execute it at MODULE scope so that a bench missing fastapi/pydantic/uvicorn is reported
# by run.py as DEPS ("never loaded: needs X") rather than as a wall of failing checks.
# Those two facts collide: discovery imports every test_*.py, so merely HAVING this file
# would install a root handler and set the root level, and every other suite in the run
# would start printing INFO lines it has never printed before. The root logger is
# therefore put back exactly as it was found, and the vehicle's own logger is held quiet
# for the duration so the few records main.py emits on the way up do not land on a runner
# that did not ask for them.
_root = logging.getLogger()
_saved_root = (_root.handlers[:], _root.level)
_neptune_log = logging.getLogger("neptune")
_saved_neptune = _neptune_log.level
_neptune_log.setLevel(logging.ERROR)
try:
    neptune = _load_app_under_test()
finally:
    _neptune_log.setLevel(_saved_neptune)
    _root.handlers[:] = _saved_root[0]
    _root.setLevel(_saved_root[1])

