class SlowConsumerTest(SocketCase):
    """ONE CLIENT THAT STOPS READING MUST NOT STOP THE VEHICLE.

    The control loop in api/main.py does the whole of the vehicle's real-time work in one
    task: it advances the simulation, RUNS THE WATCHDOG, journals the blackbox, and only
    then broadcasts. Broadcasting is `await ws.send_text(...)` per client, in a loop, and
    an awaited send does not return until the transport is willing to take the bytes. So
    a client that stops draining its socket is, mechanically, a client that can hold the
    watchdog still — and a watchdog that is held still is a failsafe that has been
    switched off by a stranger with a laptop.

    THE EXPERIMENT RUNS ONCE, IN setUpClass, and the checks below read what it recorded.
    Four different facts come out of one held condition, and running it four times would
    be four chances for the condition to arise differently; separating the ASSERTIONS is
    what makes the report legible, not separating the experiment.

    THIS CLASS IS NAMED SO THAT IT SORTS LAST. unittest runs a module's classes in name
    order, and this is the one class here that deliberately drives the app into a state
    it may not come out of. It cannot be given a server of its own — see the note on
    SERVER above, one `main.app` cannot host two lifespans — so instead it goes at the
    end, where a control loop that stayed wedged costs nothing but its own report. It
    still drains the stalled socket and checks the vehicle came back (see the last
    check), because leaving the app poisoned would be a finding of its own.

    WHAT A GREEN RESULT HERE IS WORTH. Backpressure has to be created before it can be
    survived, and creating it means filling the client's receive buffer, the server's
    send buffer and asyncio's write buffer with telemetry, which takes seconds and takes
    a different number of them on every kernel. If the window ends before the server was
    ever pushed back on, these checks watched a healthy loop under a condition that never
    arrived. `queued_bytes` — how much the stalled socket had waiting when it finally
    read — is recorded and printed in the failure messages so the reader can tell those
    two situations apart instead of taking the green on trust.
    """

    # what the experiment recorded
    gaps: list[float] = []
    frames: int = 0
    http_probes: list[tuple[int, float]] = []
    queued_bytes: int = -1
    resumed_seq: int | None = None
    resume_error: str | None = None
    failsafe_after_stall: bool | None = None
    drove_before_stall: tuple[float, float] = (-1.0, -1.0)
    thrust_after_stall: tuple[float, float] = (-1.0, -1.0)
    rcvbuf: int = -1

    @classmethod
    def setUpClass(cls):
        cls._run_experiment()

    @classmethod
    def tearDownClass(cls):
        quiesce()

    @classmethod
    def _run_experiment(cls):
        srv = SERVER
        assert srv is not None, "the server fixture never came up"
        healthy = Ws(srv.port, timeout=MAX_TELEMETRY_GAP_S)
        slow = Ws(srv.port, rcvbuf=SLOW_RCVBUF, timeout=1.0)
        cls.rcvbuf = slow.rcvbuf
        # The HTTP plane is sampled from ANOTHER THREAD, on its own connections, and
        # deliberately not from the read loop below: a blocking health request taken in
        # between two frame reads would show up as a gap in telemetry that this suite
        # caused itself, and the whole finding here is the size of those gaps. Two
        # observers, two threads, one condition.
        probes: list[tuple[int, float]] = []
        stop_probing = threading.Event()

        def _poll_health():
            while not stop_probing.wait(1.0):
                t0 = time.monotonic()
                try:
                    status, _ = srv.http("/healthz", timeout=MAX_TELEMETRY_GAP_S)
                except Exception:  # noqa: BLE001 — a failure to answer IS the reading
                    status = 0
                probes.append((status, time.monotonic() - t0))

        poller = threading.Thread(target=_poll_health, name="neptune-test-health", daemon=True)
        try:
            healthy.next_of("telemetry", timeout=DEFAULT_TIMEOUT_S)
            # ---- hold the condition, and watch the loop through the good socket ----
            poller.start()
            gaps: list[float] = []
            started = last = time.monotonic()
            frames = 0
            while time.monotonic() - started < SLOW_HOLD_S:
                try:
                    msg = healthy.recv_json()
                except (TimeoutError, OSError, WsClosed):
                    continue
                if msg.get("type") != "telemetry":
                    continue
                now = time.monotonic()
                gaps.append(now - last)
                last = now
                frames += 1
            gaps.append(time.monotonic() - last)  # the silence the window ended in
            stop_probing.set()
            poller.join(timeout=CLIENT_SETTLE_S)
            cls.gaps, cls.frames, cls.http_probes = gaps, frames, list(probes)

            # ---- while it is still held: is the failsafe still running? ----
            # The receive side of a socket is not the send side, so commands still land
            # even when nothing can be broadcast: this drives the thrusters through the
            # ws handler task and then goes quiet. If the control loop is turning, the
            # watchdog zeroes them. If it is not, a client that stopped reading has
            # switched the failsafe off.
            rov = neptune.app.state.rov
            healthy.send_json({"type": "command", "name": "arm", "c_id": "slow-arm"})
            deadline = time.monotonic() + 2.0
            while time.monotonic() < deadline and not (rov.left > 0.5 and rov.right > 0.5):
                healthy.send_json({"type": "control", "throttle": 1.0, "steer": 0.0})
                time.sleep(0.05)
            # RECORDED BEFORE THE SILENCE, because the check below is worthless without
            # it: a watchdog that did not latch on a vehicle that was never driving is
            # a watchdog behaving perfectly, and reporting that as the failsafe being
            # disabled would be this suite crying wolf about its own setup.
            cls.drove_before_stall = (rov.left, rov.right)
            time.sleep(settings.watchdog_timeout_s + WATCHDOG_SETTLE_S)
            cls.failsafe_after_stall = bool(rov._failsafe)
            cls.thrust_after_stall = (rov.left, rov.right)
            quiesce()

            # ---- end the condition, and see whether the vehicle comes back ----
            cls.queued_bytes = slow.drain()
            try:
                cls.resumed_seq = healthy.next_of("telemetry", timeout=SLOW_RESUME_S)["seq"]
            except Exception as exc:  # noqa: BLE001 — recorded, asserted on below
                cls.resume_error = f"{type(exc).__name__}: {exc}"
        finally:
            stop_probing.set()
            slow.close()
            healthy.close()

    def _evidence(self) -> str:
        return (
            f"(held {SLOW_HOLD_S:.0f}s; telemetry frames reaching the healthy client: "
            f"{self.frames}; the stalled socket had {self.queued_bytes} bytes waiting "
            f"when it finally read, with SO_RCVBUF={self.rcvbuf})"
        )

    def test_a_telemetry_kept_reaching_a_client_that_was_reading(self):
        self.assertTrue(self.gaps, "the experiment recorded nothing at all")
        worst = max(self.gaps)
        self.assertLessEqual(
            worst,
            MAX_TELEMETRY_GAP_S,
            f"a client that stopped reading stalled the control loop for {worst:.1f}s. "
            "Everything on that loop stops together — telemetry to every OTHER client, "
            "the blackbox, and the thruster watchdog — so this is not a rendering "
            f"problem, it is one stranger's socket holding the failsafe still. "
            f"{self._evidence()}",
        )

    def test_b_the_http_plane_kept_answering(self):
        """Which half stopped? This is how the report says so.

        If HTTP kept answering while telemetry stalled, the event loop is fine and the
        CONTROL LOOP is what was blocked — a precise finding. If HTTP stalled too, the
        whole process was held, which is a different and worse one.
        """
        self.assertTrue(self.http_probes, "no health probes were taken")
        bad = [p for p in self.http_probes if p[0] != 200]
        self.assertEqual(
            [],
            bad,
            f"/healthz stopped answering 200 while one client was not "
            f"reading: {self.http_probes} {self._evidence()}",
        )

    def test_c_the_failsafe_still_ran_while_a_client_was_not_reading(self):
        self.assertIsNotNone(self.failsafe_after_stall, "the experiment never reached the failsafe check")
        # The premise, checked first: a watchdog that did not fire on a vehicle that was
        # never driving is a watchdog working correctly, and the finding below would be
        # this suite misreading its own setup.
        self.assertGreater(
            min(self.drove_before_stall),
            0.5,
            "the thrusters were never driving, so there was nothing for "
            f"the failsafe to catch: {self.drove_before_stall}",
        )
        self.assertTrue(
            self.failsafe_after_stall,
            "the thrusters were driven and the control frames then stopped, and the "
            f"watchdog never latched — thrusters left at {self.thrust_after_stall}. A "
            "client that simply stops reading its socket therefore disables the one "
            f"mechanism that stops a runaway vehicle. {self._evidence()}",
        )

    def test_d_the_vehicle_comes_back_when_the_slow_client_drains(self):
        """Whatever the answer above, the app must not be permanently poisoned."""
        self.assertIsNone(
            self.resume_error,
            f"telemetry never returned after the stalled client drained "
            f"{self.queued_bytes} bytes: {self.resume_error}",
        )
        self.assertIsNotNone(self.resumed_seq)


